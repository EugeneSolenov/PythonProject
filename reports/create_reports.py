    add_line(document, f"Описание доработки на ПР{number}: {description}")
    add_line(document, f"Git-репозиторий: {GITHUB_URL}")
    add_line(
        document,
        f"4. Результат работы. В результате выполнения ПР{number}:",
        True,
    )
    add_items(document, result)
    add_line(
        document,
        "5. Вывод. Краткий вывод о результатах выполнения "
        "практической работы:",
        True,
    )
    add_line(document, conclusion)
    target_path = REPORTS_DIR / Path(path).name
    document.save(target_path)
    print(f"Отчёт сохранён: {target_path}")


