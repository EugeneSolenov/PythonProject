from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Pt

GITHUB_URL = "https://github.com/EugeneSolenov/PythonProject"


def add_line(document, text="", bold=False):
    paragraph = document.add_paragraph()
    run = paragraph.add_run(text)
    run.bold = bold
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(14)
    return paragraph


def add_items(document, items):
    for item in items:
        add_line(document, f"• {item}")


def configure(document):
    for section in document.sections:
        section.top_margin = Pt(56.7)
        section.bottom_margin = Pt(56.7)
        section.left_margin = Pt(85.0)
        section.right_margin = Pt(56.7)
    style = document.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(14)


def make_report(
    path,
    number,
    topic,
    materials,
    description,
    result,
    conclusion,
):
    document = Document()
    configure(document)
    title = add_line(
        document,
        f"ОТЧЁТ ПО ПРАКТИЧЕСКОЙ РАБОТЕ № {number}",
        True,
    )
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_line(document)
    add_line(document, "1. Общие сведения:", True)
    add_line(
        document,
        "Дисциплина: Технологии разработки приложений на базе фреймворков",
    )
    add_line(
        document,
        "Номер и тема практической работы: "
        f"Практическая работа № {number}. «{topic}»",
    )
    add_line(document, "Группа: ЭФБО-06-24")
    add_line(document, "ФИО студента: Соленов Евгений Олегович")
    add_line(document, "Год выполнения: 2026")
    add_line(document, "2. Выполненные материалы Яндекс Практикума", True)
    for section, topics in materials:
        add_line(document, f"{section}:", True)
        add_items(document, topics)
    add_line(document, "3. Индивидуальный проект:", True)
    add_line(
        document,
        "Название проекта: «Консольный менеджер персональных событий "
        "и напоминаний» (Семейный календарь)",
    )
    add_line(
        document,
        "Предметная область: персональный тайм-менеджмент, учёт памятных "
        "дат, событий и напоминаний.",
    )
    add_line(document, f"Описание доработки на ПР{number}: {description}")
    add_line(document, f"Git-репозиторий: {GITHUB_URL}")
    add_line(
        document,
        f"4. Результат работы. В результате выполнения ПР{number}:",
        True,
    )
    add_items(document, result)
    add_line(
        document,
        "5. Вывод. Краткий вывод о результатах выполнения "
        "практической работы:",
        True,
    )
    add_line(document, conclusion)
    document.save(path)


